use anyhow::Result;
use crate::domain::narrative::AnnotatedLine;
use super::engine::TtsEngine;

/// A mock TTS engine for dry-runs and testing.
/// It doesn't call a real API, just returns a tiny fake WAV buffer.
pub struct MockTtsEngine;

impl TtsEngine for MockTtsEngine {
    async fn generate_audio(&self, line: &AnnotatedLine) -> Result<Vec<u8>> {
        crate::log_info!("  [Mock TTS] Generating audio for speaker {:?}...", line.speaker.0);
        // Return a dummy 44-byte WAV header (empty audio)
        Ok(vec![
            0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x57, 0x41, 0x56, 0x45, 0x66, 0x6d, 0x74, 0x20,
            0x10, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x44, 0xac, 0x00, 0x00, 0x88, 0x58, 0x01, 0x00,
            0x02, 0x00, 0x10, 0x00, 0x64, 0x61, 0x74, 0x61, 0x00, 0x00, 0x00, 0x00,
        ])
    }
}
